"""Private local upload storage helpers."""
from __future__ import annotations

import os
import logging
import re
import base64
import secrets
from pathlib import Path
from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM


upload_log = logging.getLogger("casework.upload")
PRIVATE_UPLOAD_NAME = re.compile(r"^[0-9a-f]{48}\.(?:png|jpg|webp|pdf)$")
UPLOAD_MAGIC = b"RSAICDP\x01"
UPLOAD_NONCE_BYTES = 12
UPLOAD_TAG_BYTES = 16
UPLOAD_KEY_BYTES = 32


def is_private_upload_name(value: object) -> bool:
    """Accept only the opaque filename format generated by the intake API."""
    return isinstance(value, str) and PRIVATE_UPLOAD_NAME.fullmatch(value) is not None


def ensure_private_upload_dir(path: Path) -> None:
    """Create the upload directory and remove group/other permissions on POSIX."""
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    if os.name == "posix":
        path.chmod(0o700)


def decode_upload_encryption_key(encoded: str | None) -> bytes | None:
    """Decode the canonical base64 256-bit key configured outside the repository."""
    if not encoded:
        return None
    try:
        key = base64.b64decode(encoded, validate=True)
    except (ValueError, base64.binascii.Error):
        raise ValueError("UPLOAD_ENCRYPTION_KEY must be base64-encoded 32-byte key material")
    if len(key) != UPLOAD_KEY_BYTES or base64.b64encode(key).decode("ascii") != encoded:
        raise ValueError("UPLOAD_ENCRYPTION_KEY must be canonical base64 for exactly 32 bytes")
    return key


def write_private_upload(
    path: Path,
    content: bytes,
    encryption_key: bytes | None = None,
    associated_filename: str | None = None,
) -> None:
    """Create an exclusive private upload, encrypting and authenticating bytes when keyed."""
    if not is_private_upload_name(path.name):
        raise ValueError("Upload filename is invalid")
    stored_content = content
    if encryption_key is not None:
        if len(encryption_key) != UPLOAD_KEY_BYTES:
            raise ValueError("Upload encryption key must contain 32 bytes")
        nonce = secrets.token_bytes(UPLOAD_NONCE_BYTES)
        bound_filename = associated_filename or path.name
        if not is_private_upload_name(bound_filename):
            raise ValueError("Upload associated filename is invalid")
        associated_data = UPLOAD_MAGIC + bound_filename.encode("ascii")
        ciphertext = AESGCM(encryption_key).encrypt(nonce, content, associated_data)
        stored_content = UPLOAD_MAGIC + nonce + ciphertext
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_BINARY"):
        flags |= os.O_BINARY
    descriptor = os.open(path, flags, 0o600)
    try:
        with os.fdopen(descriptor, "wb") as destination:
            destination.write(stored_content)
    except Exception:
        # If fdopen itself failed, it did not take ownership of the descriptor.
        try:
            os.close(descriptor)
        except OSError:
            pass
        try:
            path.unlink(missing_ok=True)
        except OSError as cleanup_error:
            upload_log.warning("Could not remove incomplete private upload (error=%s)", type(cleanup_error).__name__)
        raise


def read_private_upload(
    path: Path,
    maximum_plaintext_bytes: int,
    encryption_key: bytes | None = None,
    associated_filename: str | None = None,
) -> bytes:
    """Read a bounded private upload and authenticate/decrypt it when encryption is configured."""
    if not is_private_upload_name(path.name):
        raise ValueError("Upload filename is invalid")
    if maximum_plaintext_bytes < 0:
        raise ValueError("Upload read limit must not be negative")
    maximum_stored_bytes = maximum_plaintext_bytes
    if encryption_key is not None:
        maximum_stored_bytes += len(UPLOAD_MAGIC) + UPLOAD_NONCE_BYTES + UPLOAD_TAG_BYTES
    with path.open("rb") as source:
        stored_content = source.read(maximum_stored_bytes + 1)
    if len(stored_content) > maximum_stored_bytes:
        raise ValueError("Private upload exceeds the configured size limit")
    if stored_content.startswith(UPLOAD_MAGIC):
        if encryption_key is None:
            raise ValueError("Private upload encryption key is required")
        if len(stored_content) < len(UPLOAD_MAGIC) + UPLOAD_NONCE_BYTES + UPLOAD_TAG_BYTES:
            raise ValueError("Private upload encrypted content is incomplete")
        nonce_start = len(UPLOAD_MAGIC)
        nonce = stored_content[nonce_start:nonce_start + UPLOAD_NONCE_BYTES]
        ciphertext = stored_content[nonce_start + UPLOAD_NONCE_BYTES:]
        bound_filename = associated_filename or path.name
        if not is_private_upload_name(bound_filename):
            raise ValueError("Upload associated filename is invalid")
        associated_data = UPLOAD_MAGIC + bound_filename.encode("ascii")
        try:
            plaintext = AESGCM(encryption_key).decrypt(nonce, ciphertext, associated_data)
        except InvalidTag:
            raise ValueError("Private upload authentication failed")
        if len(plaintext) > maximum_plaintext_bytes:
            raise ValueError("Private upload exceeds the configured size limit")
        return plaintext
    if encryption_key is not None:
        raise ValueError("Private upload encryption format is invalid")
    return stored_content
